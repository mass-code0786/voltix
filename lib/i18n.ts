export type TranslationKey = keyof typeof translations.en;
type TranslationMap = Partial<Record<TranslationKey, string>>;

export function getTranslator(language?: string | null) {
  const code = normalizeLanguage(language);
  const active = (translations as Record<string, TranslationMap>)[code] ?? {};
  return (key: TranslationKey) => active[key] ?? translations.en[key] ?? key;
}
